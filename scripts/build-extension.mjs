// Zero-dependency bundler for this extension's small, explicit named-import modules.
// Browser entrypoints stay classic scripts: no dynamic loading, eval or CSP changes.
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { Script } from 'node:vm'

const defaultRoot = fileURLToPath(new URL('../', import.meta.url))
const importPattern = /^import \{ ([\w, ]+) \} from '([^']+)'\r?\n/gm
const exportPattern = /^export (?:(?:async )?function|const|let) (\w+)/gm

async function bundle(root, entry, bootstrap, guard = '') {
  const sourceRoot = path.join(root, 'extension', 'src')
  const modules = new Map()
  const visiting = new Set()
  const key = file => path.relative(sourceRoot, file).split(path.sep).join('/')

  async function visit(file) {
    if (modules.has(file)) return
    if (visiting.has(file)) throw new Error(`Circular extension import: ${key(file)}`)
    const relative = path.relative(sourceRoot, file)
    if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Extension import escapes src/')
    visiting.add(file)
    const source = await fs.readFile(file, 'utf8')
    const imports = [...source.matchAll(importPattern)]
    const declarations = []
    for (const [, symbols, specifier] of imports) {
      if (!specifier.startsWith('./') && !specifier.startsWith('../')) throw new Error(`External import: ${specifier}`)
      const dependency = path.resolve(path.dirname(file), specifier)
      await visit(dependency)
      for (const name of symbols.split(',').map(s => s.trim())) {
        if (!modules.get(dependency).exports.includes(name)) throw new Error(`Missing export ${name} from ${specifier}`)
      }
      declarations.push(`const { ${symbols} } = modules[${JSON.stringify(key(dependency))}]`)
    }
    const exported = [...source.matchAll(exportPattern)].map(match => match[1])
    const body = source.replace(importPattern, '').replace(/^export (?=(?:async )?function|const|let)/gm, '')
    if (/^\s*(?:import|export)\s/m.test(body)) throw new Error(`Unsupported module syntax in ${key(file)}`)
    modules.set(file, { exports: exported, body, declarations })
    visiting.delete(file)
  }

  const entryFile = path.join(sourceRoot, entry)
  await visit(entryFile)
  const chunks = ['// GENERATED by scripts/build-extension.mjs. Edit extension/src/ instead.', '(() => {', guard, 'const modules = Object.create(null)']
  for (const [file, module] of modules) {
    chunks.push(`\n// ---- ${key(file)} ----`, `modules[${JSON.stringify(key(file))}] = (() => {`, ...module.declarations, module.body.trimEnd(), `return { ${module.exports.join(', ')} }`, '})()')
  }
  if (bootstrap) chunks.push(bootstrap(key(entryFile)))
  chunks.push('})()', '')
  const output = chunks.join('\n')
  new Script(output, { filename: entry })
  return output
}

export async function buildExtension({ root = defaultRoot, check = false, publicBuild = false } = {}) {
  // The repository ships public artifacts and no relay/config.json (it holds the
  // local token), so a clean clone must still be able to build and verify.
  let config
  try {
    config = JSON.parse(await fs.readFile(path.join(root, 'relay', 'config.json'), 'utf8'))
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
    config = { port: 8123, token: '' }
  }
  if (!Number.isInteger(config.port) || config.port < 1 || config.port > 65535) throw new Error('config.port must be an integer between 1 and 65535')
  if (config.token !== '' && (typeof config.token !== 'string' || !config.token)) throw new Error('config.token must be a string')
  // A public build ships no secret: the plugin materialises a paired copy of the
  // extension at runtime, so the token never lands in a repository or tarball.
  const endpoint = { worker: `http://127.0.0.1:${config.port}`, token: publicBuild ? '' : config.token }
  const manifest = JSON.parse(await fs.readFile(path.join(root, 'extension', 'src', 'manifest.json'), 'utf8'))
  // Match patterns carry no port, and a headless user may run the worker on any
  // port, so grant the whole loopback host instead of one baked-in port.
  for (const origin of ['http://127.0.0.1/*', 'http://localhost/*']) {
    if (!manifest.host_permissions.includes(origin)) manifest.host_permissions.push(origin)
  }
  const optionsDir = path.join(root, 'extension', 'src', 'options')
  const outputs = {
    'content.js': await bundle(root, 'content/runtime.mjs', null, 'if (window.__gptRelayLoaded) return\nwindow.__gptRelayLoaded = true'),
    'background.js': await bundle(root, 'background/messages.mjs', key => `modules[${JSON.stringify(key)}].registerMessages(${JSON.stringify(endpoint)})`),
    'manifest.json': JSON.stringify(manifest, null, 2) + '\n',
    'options.html': await fs.readFile(path.join(optionsDir, 'options.html'), 'utf8'),
    'options.js': await fs.readFile(path.join(optionsDir, 'options.js'), 'utf8'),
  }
  for (const [name, output] of Object.entries(outputs)) {
    const target = path.join(root, 'extension', name)
    if (check) {
      const current = await fs.readFile(target, 'utf8').catch(() => null)
      // The committed artifacts are public builds (no token); a local build
      // injects the developer's token, so ignore that one field when comparing.
      const mask = text => String(text ?? '').replace(/("token"\s*:\s*")[^"]*(")/g, '$1$2')
      if (mask(current) !== mask(output)) throw new Error(`Stale extension/${name}; run node scripts/build-extension.mjs`)
    } else {
      await fs.writeFile(target, output, 'utf8')
    }
  }
  return Object.keys(outputs)
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    const check = process.argv.includes('--check')
    const files = await buildExtension({ check, publicBuild: process.argv.includes('--public') })
    console.log(`Extension ${check ? 'verified' : 'built'}: ${files.join(', ')}`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
